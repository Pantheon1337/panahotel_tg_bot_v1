# Вспомогательная функция для получения роли пользователя
async def get_user_role(user_id: int) -> UserRole:
    session = Session()
    user = session.query(User).filter_by(telegram_id=user_id).first()
    session.close()
    # Если пользователь не найден, возвращаем роль стажера по умолчанию
    return user.role if user else UserRole.TRAINEE